#!/usr/bin/env python3
"""Runs Undertow's conformance cases through real Tidal.

Reads tests/conformance/cases.txt, writes Cases.hs for the tidal-oracle
program, runs it with cabal, and saves its output as
tests/conformance/tidal-expected.txt. Needs GHC and cabal-install; Tidal
itself is fetched by cabal on the first run.
"""

import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
ORACLE = ROOT / "tools" / "tidal-oracle"
CASES = ROOT / "tests" / "conformance" / "cases.txt"
EXPECTED = ROOT / "tests" / "conformance" / "tidal-expected.txt"


def read_cases():
    cases = []
    for number, line in enumerate(CASES.read_text().splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        fields = line.split(None, 3)
        if len(fields) != 4 or fields[2] not in ("mini", "note", "expr") or not fields[1].isdigit():
            sys.exit(f"{CASES}:{number}: expected 'id cycles mini|note|expr source'")
        case_id, cycles, kind, source = fields
        cases.append((case_id, int(cycles), kind, source))
    return cases


def haskell_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_cases_module(cases):
    lines = [
        "-- Generated by generate.py from tests/conformance/cases.txt; do not edit.",
        "{-# LANGUAGE OverloadedStrings #-}",
        "module Cases (cases) where",
        "",
        "import Sound.Tidal.Context",
        "",
        "-- Notes print as exact fractions, so both sides format them the same way.",
        "asNotes :: Pattern Note -> Pattern String",
        "asNotes = fmap (showFraction . toRational . unNote)",
        "  where",
        "    showFraction r",
        "      | denominator r == 1 = show (numerator r)",
        '      | otherwise = show (numerator r) ++ "/" ++ show (denominator r)',
        "",
        "cases :: [(String, Int, Pattern String)]",
        "cases =",
    ]
    for index, (case_id, cycles, kind, source) in enumerate(cases):
        if kind == "mini":
            expression = haskell_string(source)
        elif kind == "note":
            expression = f"asNotes {haskell_string(source)}"
        else:
            expression = f"({source})"
        opener = "[" if index == 0 else ","
        lines.append(f"  {opener} ({haskell_string(case_id)}, {cycles}, {expression})")
    lines.append("  ]" if cases else "  []")
    (ORACLE / "Cases.hs").write_text("\n".join(lines) + "\n")


def main():
    cases = read_cases()
    write_cases_module(cases)
    result = subprocess.run(["cabal", "run", "-v0", "tidal-oracle"], cwd=ORACLE, capture_output=True, text=True)
    if result.returncode != 0:
        sys.stderr.write(result.stderr)
        sys.exit("tidal-oracle failed")
    EXPECTED.write_text("# Generated by tools/tidal-oracle/generate.py; do not edit.\n" + result.stdout)
    print(f"Wrote {len(cases)} cases to {EXPECTED.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
